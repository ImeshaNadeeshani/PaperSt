const { chromium } = require('@playwright/test');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1536, height: 1024 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5175/category/notebooks');
  await page.locator('.nb-card').first().waitFor();
  await page.locator('.nb-heart').first().click();
  await page.locator('.nb-bag').first().click();
  await page.locator('.nb-check').filter({ hasText: 'Notebooks' }).click();
  console.log('Filtered cards:', await page.locator('.nb-card').count());
  await page.getByLabel('Sort products').selectOption('Price: high to low');
  await page.getByRole('button', { name: 'List', exact: true }).click();
  if (!await page.locator('.nb-list').count()) throw Error('List view did not activate');
  await page.locator('.nb-check').filter({ hasText: 'Notebooks' }).click();
  await page.getByLabel('Sort products').selectOption('Featured');
  await page.getByRole('button', { name: 'Grid', exact: true }).click();
  await page.screenshot({ path: 'artifacts/notebooks-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Filters', exact: true }).click();
  if (!await page.locator('.nb-sidebar.open').count()) throw Error('Mobile drawer did not open');
  await page.getByRole('button', { name: 'Close filters' }).click();
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Mobile overflow');
  await page.screenshot({ path: 'artifacts/notebooks-mobile.png' });
  await browser.close();
  if (errors.length) throw Error(errors.join('\n'));
  console.log('Desktop and mobile interaction checks passed.');
})();
